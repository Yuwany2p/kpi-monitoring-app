-- H2 Schema compatible with PostgreSQL mode
CREATE SEQUENCE IF NOT EXISTS seq_kpi START WITH 1;
CREATE SEQUENCE IF NOT EXISTS seq_detail_kpi START WITH 1;
CREATE SEQUENCE IF NOT EXISTS seq_upload START WITH 1;

CREATE TABLE IF NOT EXISTS karyawan (
  npk            VARCHAR(10) PRIMARY KEY,
  nama_karyawan  VARCHAR(100) NOT NULL,
  gender         VARCHAR(25),
  bagian         VARCHAR(100),
  role           VARCHAR(20) NOT NULL,
  username       VARCHAR(50) NOT NULL UNIQUE,
  password       VARCHAR(100) NOT NULL,
  status_aktif   BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS kpi (
  id_kpi             VARCHAR(10) PRIMARY KEY,
  nama_kpi           VARCHAR(100) NOT NULL,
  persentase_bobot   NUMERIC(5,2) NOT NULL DEFAULT 0,
  persentase_progres NUMERIC(5,2) NOT NULL DEFAULT 0,
  level              VARCHAR(100),
  kategori           VARCHAR(100),
  periode            VARCHAR(20),
  status             VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
  dibuat_oleh        VARCHAR(10) NOT NULL,
  FOREIGN KEY (dibuat_oleh) REFERENCES karyawan(npk)
);

CREATE TABLE IF NOT EXISTS kpi_penanggung_jawab (
  id_kpi  VARCHAR(10) NOT NULL,
  npk     VARCHAR(10) NOT NULL,
  PRIMARY KEY (id_kpi, npk),
  FOREIGN KEY (id_kpi) REFERENCES kpi(id_kpi) ON DELETE CASCADE,
  FOREIGN KEY (npk) REFERENCES karyawan(npk)
);

CREATE TABLE IF NOT EXISTS detail_kpi (
  id_detail_kpi      VARCHAR(10) PRIMARY KEY,
  id_kpi             VARCHAR(10) NOT NULL,
  npk_pic            VARCHAR(10),
  dibuat_oleh        VARCHAR(10) NOT NULL,
  nama_aktivitas_kpi VARCHAR(250) NOT NULL,
  persentase_bobot   NUMERIC(5,2) NOT NULL,
  persentase_progres NUMERIC(5,2) NOT NULL DEFAULT 0,
  deadline           DATE,
  status             VARCHAR(20) NOT NULL DEFAULT 'OPEN',
  FOREIGN KEY (id_kpi) REFERENCES kpi(id_kpi) ON DELETE CASCADE,
  FOREIGN KEY (npk_pic) REFERENCES karyawan(npk),
  FOREIGN KEY (dibuat_oleh) REFERENCES karyawan(npk)
);

CREATE TABLE IF NOT EXISTS upload_file (
  id_upload          VARCHAR(10) PRIMARY KEY,
  id_detail_kpi      VARCHAR(10) NOT NULL,
  nama_file          VARCHAR(100),
  path               VARCHAR(255),
  persentase_progres NUMERIC(5,2) NOT NULL,
  catatan            TEXT,
  tanggal_upload     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (id_detail_kpi) REFERENCES detail_kpi(id_detail_kpi) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS approval_log (
  id_log         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_detail_kpi  VARCHAR(10) NOT NULL,
  npk            VARCHAR(10) NOT NULL,
  level          VARCHAR(10) NOT NULL,
  aksi           VARCHAR(10) NOT NULL,
  catatan        TEXT,
  tanggal        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (id_detail_kpi) REFERENCES detail_kpi(id_detail_kpi) ON DELETE CASCADE,
  FOREIGN KEY (npk) REFERENCES karyawan(npk)
);

